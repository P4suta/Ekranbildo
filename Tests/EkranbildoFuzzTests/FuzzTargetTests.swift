@testable import EkranbildoFuzz
import EkranbildoGeometry
import Foundation
import Testing

@Suite("Fuzz targets")
struct FuzzTargetTests {

    @Test("No target crashes on an awkward input", arguments: FuzzTarget.all, Corpus.awkward)
    func awkwardInputs(target: FuzzTarget, input: [UInt8]) {
        target.accept(input)
    }

    @Test("No target crashes on nothing at all", arguments: FuzzTarget.all)
    func emptyInput(target: FuzzTarget) {
        target.accept([])
    }

    @Test("No target crashes on generated bytes", arguments: FuzzTarget.all)
    func generatedInputs(target: FuzzTarget) {
        var generator = SplitMix64(seed: Corpus.seed)
        for _ in 0..<Corpus.rounds {
            target.accept(Corpus.bytes(using: &generator))
        }
    }

    @Test("No target crashes on something that nearly parses", arguments: FuzzTarget.all)
    func nearlyValidInputs(target: FuzzTarget) {
        var generator = SplitMix64(seed: Corpus.seed)
        for seed in Corpus.seeds {
            for _ in 0..<Corpus.rounds {
                target.accept(Corpus.corrupted(Array(seed.utf8), using: &generator))
            }
        }
    }

    @Test("Every target has a name and is reachable")
    func everyTargetIsNamed() {
        #expect(FuzzTarget.all.allSatisfy { !$0.name.isEmpty })
        let names = FuzzTarget.all.map(\.name)
        #expect(Set(names).count == names.count)
    }

    @Test("The same seed gives the same bytes")
    func generationIsDeterministic() {
        var first = SplitMix64(seed: Corpus.seed)
        var second = SplitMix64(seed: Corpus.seed)
        #expect(Corpus.bytes(using: &first) == Corpus.bytes(using: &second))
    }

    @Test("Corrupting is a change, not a rewrite")
    func corruptionKeepsMost() {
        var generator = SplitMix64(seed: 1)
        let original = Array(String(repeating: "a", count: 200).utf8)
        let corrupted = Corpus.corrupted(original, using: &generator)
        let same = zip(original, corrupted).filter { $0 == $1 }.count
        #expect(same > original.count / 2)
    }
}
